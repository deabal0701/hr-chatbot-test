                  PEE_APPR_RESULT D,
                  VI_FRM_PHM_EMP E
            WHERE     A.PEE_DEFINITION_ID = B.PEE_DEFINITION_ID
                  AND B.APPR_ID = C.APPR_ID
                  AND C.RATEE_ID = D.RATEE_ID
