                  E.EMP_NO,
                  E.EMP_NM,
                  CASE
                     WHEN D.FIXED_SCORE > 0 THEN D.FIXED_SCORE
                     ELSE NULL
                  END
                     AS APPR_SCORE,
                  F_FRM_CODE_NM (E.COMPANY_CD,
                                 E.LOCALE_CD,
                                 'PEE_APPR_GRADE_CD',
                                 D.FIXED_GRADE,
                                 C.END_YMD,
